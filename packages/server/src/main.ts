/**
 * Composition root: builds the real dependencies and wires them.
 *
 * Environment:
 * - SSO_DB: SQLite path (default `sso.sqlite`, gitignored); `:memory:` for a throwaway world.
 * - SSO_CONTENT: the pack a new world is created with, `classic` (default) or `minimal`. Read only
 *   when the server creates the database; afterwards it does nothing (a line says so when it
 *   disagrees with the world).
 * - PORT: HTTP/WebSocket port (default 3000).
 * - NODE_ENV=development: live reload (`bun run dev`); anything else serves the minified build with
 *   the security headers.
 * - SSO_PROXY_HOPS: how many reverse proxies stand in front (default 0: the socket's address).
 * - SSO_FRAME_ANCESTORS: the CSP `frame-ancestors` value; unset adds none.
 * - SSO_SAVE_INTERVAL, SSO_RECONNECT_GRACE, SSO_SOCKETS_PER_IP: server infrastructure
 *   (config.ts); a value that does not read refuses startup.
 * - SSO_CRASH_AT: a named crash point where the process kills itself (tests only).
 * - SSO_PERF_OUT: a file path; once a second one JSON line is appended with tick timing by phase,
 *   traffic, memory and database growth (written by `bun run perf`, see docs/performance.md).
 *   Unset: nothing is timed or written.
 *
 * Whatever the setting, a minute with a dropped tick or a tick over 25 ms logs one line
 * (`tick lag in the last minute: ...`).
 */
