/** Ticks in the lag line's window: one minute. */
export const LAG_WINDOW_TICKS = 1200;

/** Generated by `bun run assets:build` (packages/data/build/assets.ts), gitignored. */
export const ASSETS_DIR = join(import.meta.dir, "..", "..", "data", "assets");

export interface ServerOptions {
  dbPath: string;
  port: number;
  development: boolean;
  /** Defaults to the system clock. Tests pass a manual one and drive `tickNow`. */
  clock?: Clock;
  /** false: the caller advances the sim with `tickNow` (deterministic tests). */
  autoTick?: boolean;
  isoNow?: () => string;
  /** Defaults to `Math.random`. Tests pass a seeded or scripted one. */
  rng?: Rng;
  /** Runs after migrations, before the game loads settings (tests add maps and settings). */
  prepare?: (db: Db) => void;
  /** Reverse proxies in front (`SSO_PROXY_HOPS`); 0 = the socket's address. */
  proxyHops?: number;
  /** Server infrastructure (`SSO_SAVE_INTERVAL` and the rest); unset fields keep their default. */
  config?: Partial<ServerConfig>;
  /** CSP `frame-ancestors` value (`SSO_FRAME_ANCESTORS`). */
  frameAncestors?: string;
  /** Prebuilt client directory (`SSO_CLIENT_DIR`, default `dist/client` in production). */
  clientDir?: string;
  /** Receives throws caught at the game's entry points (default: `console.error`). */
  onFault?: (where: string, err: unknown) => void;
  /** Named crash windows (`SSO_CRASH_AT`, tests). */
  crashPoint?: (label: string) => void;
  /** `SSO_PERF_OUT`: where the perf rig's once-a-second lines go. */
  perfOut?: string;
  /** Receives the tick lag line (default `console.warn`). */
  onLag?: (line: string) => void;
  /** Bytes waiting on a socket (tests make one look behind; default the socket's own). */
  backlogOf?: GatewayOptions["backlogOf"];
  /** The folders of the packs the release ships, by id (tests pass a changed copy). */
  releasePacks?: Readonly<Record<string, string>>;
  /** Ends the process after too many failed ticks (tests record it; default `process.exit`). */
  exit?: (code: number) => void;
}

/** Consecutive throwing ticks (1 s) after which the server saves and exits. */
export const TICK_FAILURE_LIMIT = 20;

export type RunningServer = {
  url: URL;
  /** Runs `n` sim ticks immediately (tests). */
  tickNow(n?: number): void;
  /** The live database (tests only: roles, inspection). */
  db: Db;
  /** The live game (tests only: inspection and setting up a scene). */
  game: Game;
  /** Traffic since the last call, and ticks dropped so far (tests and the rig). */
  stats(): { gateway: GatewayStats; droppedTicks: number };
  stop(): Promise<void>;
};

/** Starts the whole server. Also used by the bot E2E harness. */
export function startServer(options: ServerOptions): RunningServer {
  const clock = options.clock ?? systemClock;
  const db = openDatabase(options.dbPath);
  migrate(db);
  options.prepare?.(db);
  let gateway: Gateway | null = null;
  // The content store: the installed packs (Classic, read from the release) with the operator's
  // published changes on top. It is installed before the game loads anything, and each publish
  // swaps it in and tells every client.
  let live: Game | null = null;
  const isoNow = options.isoNow ?? (() => new Date().toISOString());
  const content = new ContentService({
    db,
    now: isoNow,
    releasePacks: options.releasePacks ?? RELEASE_PACK_DIRS,
    log: (line) => console.log(line),
    onPublish: (store) => {
      installContent(store);
      live?.contentPublished(store.hash);
    },
  });
  installContent(content.store());
  // The minute window behind the operator's lag line, and (only with a perf file) the per-phase
  // probe and its one-second window.
  const lagStats = createTickStats();
  const perfStats = createTickStats();
  const probe = options.perfOut
    ? createTickProbe(
        () => performance.now(),
        (total, phases) => perfStats.record(total, phases),
      )
    : undefined;
  const game = createGame({
    probe,
    db,
    content,
    send: (to, msg) => gateway?.send(to, msg),
    isoNow,
    rng: options.rng ?? systemRng,
    kick: (to, text) => gateway?.kick(to, text),
    dropOtherSessions: (id) => gateway?.dropOtherSessions(id),
    onFault: options.onFault,
    crashPoint: options.crashPoint,
    config: { ...DEFAULT_SERVER_CONFIG, ...options.config },
  });
  live = game;
  gateway = startGateway({
    port: options.port,
    development: options.development,
    game,
    content: () => content.clientCopy(),
    releaseArt: () => content.installedPacks().some((p) => p.id === "classic"),
    clock,
    assetsDir: ASSETS_DIR,
    proxyHops: options.proxyHops ?? 0,
    frameAncestors: options.frameAncestors,
    clientDir: options.clientDir,
    backlogOf: options.backlogOf,
  });
  let failures = 0;
  const exit = options.exit ?? ((code: number) => process.exit(code));
  let windowTicks = 0;
  const onLag = options.onLag ?? ((line: string) => console.warn(line));
  const loop: TickLoop = new TickLoop({
    clock,
    onDropped: (n) => {
      lagStats.addDropped(n);
      perfStats.addDropped(n);
    },
    onTick: () => {
      const began = performance.now();
      const ok = game.tick();
      lagStats.record(performance.now() - began);
      windowTicks += 1;
      if (windowTicks >= LAG_WINDOW_TICKS) {
        windowTicks = 0;
        const line = lagLine(lagStats.window(), gateway?.online() ?? 0);
        lagStats.reset();
        if (line) {
          onLag(line);
        }
      }
      if (ok) {
        failures = 0;
        return;
      }
      failures += 1;
      if (failures >= TICK_FAILURE_LIMIT) {
        console.error(`${failures} ticks in a row failed: saving and exiting`);
        void stop().then(() => exit(1));
      }
    },
  });
  if (options.autoTick !== false) {
    loop.start();
  }
  const gw = gateway;
  let perfTimer: ReturnType<typeof setInterval> | null = null;
  if (options.perfOut) {
    const sample = createPerfWriter({
      path: options.perfOut,
      db,
      dbPath: options.dbPath === ":memory:" ? null : options.dbPath,
      stats: perfStats,
      traffic: () => gw.takeStats(),
      dropped: () => loop.droppedTicks,
      lateness: () => loop.takeLateness(),
      now: () => Date.now(),
    });
    perfTimer = setInterval(sample, 1000);
  }
  let stopped: Promise<void> | null = null;
  const stop = () => {
    stopped ??= (async () => {
      loop.stop();
      if (perfTimer) {
        clearInterval(perfTimer);
      }
      game.saveAll();
      await gw.stop();
      // Closing the sockets logged everyone out: their logouts are written before the close.
      game.flushLogs();
      // `true` finalizes the statements the persistence modules made with `db.prepare` and closes
      // now. A plain close() leaves the connection open until GC finalizes them, and that late close
      // checkpoints the WAL under an exclusive lock: a process opening the file at that moment gets
      // SQLITE_BUSY ("database is locked") and fails to start.
      db.close(true);
    })();
    return stopped;
  };
  return {
    url: gw.url,
    db,
    game,
    stats: () => ({ gateway: gw.takeStats(), droppedTicks: loop.droppedTicks }),
    tickNow(n = 1) {
      for (let i = 0; i < n; i++) {
        if (!game.tick()) {
          throw new Error("a tick threw (see the fault log)");
        }
      }
    },
    stop,
  };
}

/** The `SSO_*` infrastructure variables, or an exit naming each one that does not read. */
function readConfigOrExit(): ServerConfig {
  const r = readServerConfig(process.env);
  if (!r.ok) {
    for (const e of r.errors) {
      console.error(e);
    }
    process.exit(1);
  }
  return r.config;
}

/** `SSO_PROXY_HOPS`: an integer >= 0, or an exit with a message. */
function readProxyHops(raw: string | undefined): number {
  if (raw === undefined || raw === "") {
    return 0;
  }
  const n = Number(raw);
  if (!Number.isInteger(n) || n < 0) {
    console.error(`SSO_PROXY_HOPS must be a whole number >= 0, got "${raw}"`);
    process.exit(1);
  }
  return n;
}

if (import.meta.main) {
  const crashAt = process.env.SSO_CRASH_AT;
  const server = startServer({
    dbPath: process.env.SSO_DB ?? "sso.sqlite",
    port: Number(process.env.PORT ?? 3000),
    development: process.env.NODE_ENV === "development",
    proxyHops: readProxyHops(process.env.SSO_PROXY_HOPS),
    config: readConfigOrExit(),
    frameAncestors: process.env.SSO_FRAME_ANCESTORS || undefined,
    clientDir: process.env.SSO_CLIENT_DIR || undefined,
    perfOut: process.env.SSO_PERF_OUT || undefined,
    crashPoint: crashAt
      ? (label) => {
          if (label === crashAt) {
            process.kill(process.pid, "SIGKILL");
          }
        }
      : undefined,
  });
  console.log(`Second Star Online listening on ${server.url}`);
  // docker stop sends SIGTERM: save and leave cleanly; a second signal exits at once.
  let stopping = false;
  const onSignal = (sig: string) => {
    if (stopping) {
      process.exit(1);
    }
    stopping = true;
    console.log(`${sig}: saving and stopping`);
    void server.stop().then(() => process.exit(0));
  };
  process.on("SIGTERM", () => onSignal("SIGTERM"));
  process.on("SIGINT", () => onSignal("SIGINT"));
}
