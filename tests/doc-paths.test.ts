/**
 * The docs point at real things: every backticked repo path exists, the identifier named right after
 * a file is in that file, and every relative markdown link (and same-document anchor) resolves.
 * Docs in scope: `docs/*.md` and `docs/guides/*.md`, except a doc that marks itself frozen in its
 * first lines. Fenced code blocks are skipped.
 */
import { describe, expect, test } from "bun:test";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve } from "node:path";

import ts from "typescript";

const ROOT = join(import.meta.dir, "..");

/** Backticked spans that look like repo paths but are examples, each with its reason. */
const EXAMPLES: ReadonlyArray<{ path: string; reason: string }> = [
  { path: "packages/data/assets/sounds/", reason: "generated by the asset build" },
  { path: "packages/data/assets/", reason: "generated by the asset build" },
  { path: "assets/added/items/Frost Bow.png", reason: "an icon a modder adds" },
];

const PATH_PREFIXES = ["packages/", "tests/", "tools/", "docs/", "assets/"];
const FILE_EXTENSION = /\.(?:ts|md|json|sql|tsv|py|png|js|css|html)$/;

interface Doc {
  file: string;
  /** Lines outside fenced code blocks, with their 1-based numbers. */
  lines: { n: number; text: string }[];
}

function docFiles(): string[] {
  const out: string[] = [
    "README.md",
    "AGENTS.md",
    "CLAUDE.md",
    "LICENSE",
    "NOTICE",
    "assets/added/README.md",
    "packages/data/content/README.md",
    "packages/server/src/systems/README.md",
    "tools/README.md",
  ].filter((file) => existsSync(join(ROOT, file)));
  for (const dir of ["docs", join("docs", "guides")]) {
    const abs = join(ROOT, dir);
    if (!existsSync(abs)) {
      continue;
    }
    for (const name of readdirSync(abs).sort()) {
      if (name.endsWith(".md") && statSync(join(abs, name)).isFile()) {
        out.push(join(dir, name));
      }
    }
  }
  return out;
}

function loadDocs(): Doc[] {
  const docs: Doc[] = [];
  for (const file of docFiles()) {
    const all = readFileSync(join(ROOT, file), "utf8").split("\n");
    if (all.slice(0, 5).some((l) => l.startsWith("> **Frozen"))) {
      continue;
    }
    let fenced = false;
    const lines: Doc["lines"] = [];
    all.forEach((text, i) => {
      if (text.trimStart().startsWith("```")) {
        fenced = !fenced;
        return;
      }
      if (!fenced) {
        lines.push({ n: i + 1, text });
      }
    });
    docs.push({ file, lines });
  }
  return docs;
}

interface Span {
  text: string;
  start: number;
  end: number;
}

function spansOf(line: string): Span[] {
  return [...line.matchAll(/`([^`]+)`/g)].map((m) => ({
    text: m[1] as string,
    start: m.index as number,
    end: (m.index as number) + m[0].length,
  }));
}

/** The repo path a span names, or null when it is not one (or is a pattern or an example). */
function repoPath(span: string, doc: string): string | null {
  const isRelative = span.startsWith("../") || span.startsWith("./");
  if (!isRelative && !PATH_PREFIXES.some((p) => span.startsWith(p))) {
    return null;
  }
  if (/[*<>{}…]|\.\.\./.test(span)) {
    return null;
  }
  // A trailing line reference: `:82`, `:82-90` or a list of them, `:82, 111-113`.
  const clean = span.replace(/:\d+(?:-\d+)?(?:, ?\d+(?:-\d+)?)*$/, "");
  const path = isRelative ? relative(ROOT, resolve(ROOT, dirname(doc), clean)) : clean;
  return EXAMPLES.some((e) => e.path === path) ? null : path;
}

const IDENTIFIER = /^[A-Za-z_$][\w$.#]*$/;
const isIdentifier = (s: string) => IDENTIFIER.test(s) && !FILE_EXTENSION.test(s);

/** Match code tokens rather than text in comments, strings, or import/export declarations. */
function containsCodeIdentifier(source: string, name: string, file = "source.ts"): boolean {
  const tree = ts.createSourceFile(
    file,
    source,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith(".tsx") ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  let found = false;
  function visit(node: ts.Node): void {
    if (
      ts.isImportDeclaration(node) ||
      ts.isImportEqualsDeclaration(node) ||
      ts.isExportDeclaration(node)
    ) {
      return;
    }
    if (ts.isIdentifier(node) && !name.includes(".") && !name.includes("#") && node.text === name) {
      found = true;
    }
    if (
      (ts.isPropertyAccessExpression(node) || ts.isQualifiedName(node)) &&
      node.getText(tree) === name
    ) {
      found = true;
    }
    if (ts.isClassDeclaration(node) && node.name && name.startsWith(`${node.name.text}.#`)) {
      const member = name.slice(node.name.text.length + 1);
      if (
        node.members.some((m) => m.name && ts.isPrivateIdentifier(m.name) && m.name.text === member)
      ) {
        found = true;
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(tree);
  return found;
}

/** What GitHub makes of a heading: the anchor it can be linked by. */
function slugOf(heading: string): string {
  return heading
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1")
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N} _-]/gu, "")
    .replace(/ /g, "-");
}

function slugsOf(doc: Doc): Set<string> {
  const seen = new Map<string, number>();
  const out = new Set<string>();
  for (const { text } of doc.lines) {
    const m = text.match(/^#{1,6}\s+(.*?)\s*#*\s*$/);
    if (!m) {
      continue;
    }
    const base = slugOf(m[1] as string);
    const n = seen.get(base) ?? 0;
    seen.set(base, n + 1);
    out.add(n === 0 ? base : `${base}-${n}`);
  }
  return out;
}

function linkProblem(root: string, document: Doc, target: string): string | null {
  if (/^[a-z][a-z0-9+.-]*:/i.test(target)) {
    return null;
  }
  const [file = "", anchor] = target.split("#", 2);
  let rel = file;
  try {
    rel = decodeURIComponent(file);
  } catch {
    /* use the raw target */
  }
  const absolute =
    file === "" ? join(root, document.file) : resolve(root, dirname(document.file), rel);
  if (!existsSync(absolute)) {
    return `${target} does not exist`;
  }
  if (anchor && statSync(absolute).isFile() && absolute.endsWith(".md")) {
    const lines = readFileSync(absolute, "utf8")
      .split("\n")
      .map((text, i) => ({ n: i + 1, text }));
    if (!slugsOf({ file: absolute, lines }).has(decodeURIComponent(anchor))) {
      return `no heading for ${target}`;
    }
  }
  return null;
}

describe("doc paths", () => {
  const docs = loadDocs();

  test("code identifiers exclude text and imports while retaining real references", () => {
    const source =
      `import { imported } from "module";
export { reexported } from "module";
// commentOnly
const longerName = "stringOnly";
function actual() { return actual(); }
const template = ` +
      "`templateOnly $" +
      "{interpolated}`" +
      `;
const result = alpha.beta.gamma;
class Owner { #secret = 1; }
class Other { #different = 2; }`;
    for (const name of ["actual", "interpolated", "alpha.beta.gamma", "Owner.#secret"]) {
      expect(containsCodeIdentifier(source, name)).toBe(true);
    }
    for (const name of [
      "commentOnly",
      "stringOnly",
      "templateOnly",
      "longer",
      "imported",
      "reexported",
      "gamma.beta.alpha",
      "alpha.gamma",
      "Other.#secret",
    ]) {
      expect(containsCodeIdentifier(source, name)).toBe(false);
    }
  });

  test("relative backticked paths resolve against the document", () => {
    expect(repoPath("../original/usage.md", "assets/added/README.md")).toBe(
      "assets/original/usage.md",
    );
    const missing = repoPath("../original/missing.md", "assets/added/README.md");
    expect(missing).not.toBeNull();
    expect(existsSync(join(ROOT, missing!))).toBe(false);
  });

  test("every backticked repo path in the docs exists", () => {
    expect(docs.length).toBeGreaterThan(2);
    const missing: string[] = [];
    for (const d of docs) {
      for (const { n, text } of d.lines) {
        for (const s of spansOf(text)) {
          const path = repoPath(s.text, d.file);
          if (path !== null && !existsSync(join(ROOT, path))) {
            missing.push(`${d.file}:${n}: ${s.text}`);
          }
        }
      }
    }
    expect(missing).toEqual([]);
  });

  test("the identifier named right after a file path is in that file", () => {
    const wrong: string[] = [];
    for (const d of docs) {
      for (const { n, text } of d.lines) {
        const spans = spansOf(text);
        spans.forEach((s, i) => {
          const path = repoPath(s.text, d.file);
          const abs = path === null ? null : join(ROOT, path);
          if (path === null || abs === null || !existsSync(abs) || !statSync(abs).isFile()) {
            return;
          }
          const source = readFileSync(abs, "utf8");
          for (let j = i + 1; j < spans.length; j++) {
            const prev = spans[j - 1] as Span;
            const next = spans[j] as Span;
            const between = text.slice(prev.end, next.start);
            const ok = j === i + 1 ? between === " (" || between === ", " : between === ", ";
            if (!ok || !isIdentifier(next.text)) {
              break;
            }
            if (
              !(path.endsWith(".ts") || path.endsWith(".tsx")
                ? containsCodeIdentifier(source, next.text, path)
                : source.includes(next.text))
            ) {
              wrong.push(`${d.file}:${n}: ${next.text} is not in ${path}`);
            }
          }
        });
      }
    }
    expect(wrong).toEqual([]);
  });

  test("nested links reject missing files and headings", () => {
    const root = mkdtempSync(join(tmpdir(), "sso-doc-link-"));
    try {
      mkdirSync(join(root, "docs", "guides"), { recursive: true });
      writeFileSync(join(root, "docs", "README.md"), "# Available heading\n");
      const doc = { file: "docs/guides/example.md", lines: [] };
      expect(linkProblem(root, doc, "../README.md#available-heading")).toBeNull();
      expect(linkProblem(root, doc, "../README.md#missing-heading")).not.toBeNull();
      expect(linkProblem(root, doc, "../missing.md")).not.toBeNull();
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  test("every relative markdown link in the docs resolves", () => {
    const broken: string[] = [];
    for (const d of docs) {
      for (const { n, text } of d.lines) {
        const plain = text.replace(/`[^`]*`/g, "");
        for (const m of plain.matchAll(/\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
          const target = m[1] as string;
          const problem = linkProblem(ROOT, d, target);
          if (problem) {
            broken.push(`${d.file}:${n}: ${problem}`);
          }
        }
      }
    }
    expect(broken).toEqual([]);
  });
});
